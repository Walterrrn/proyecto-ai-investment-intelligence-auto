"""Signals and recommendations endpoint."""

from typing import List, Optional
from fastapi import APIRouter, Depends
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select
from pydantic import BaseModel
from src.core.database import get_db
from src.models.signal import Signal

router = APIRouter()


class SignalRead(BaseModel):
    id: int
    asset_id: int
    source_engine: str
    direction: str
    reference_price: float
    entry_zone_min: Optional[float] = None
    entry_zone_max: Optional[float] = None
    stop_loss_price: Optional[float] = None
    target_price: Optional[float] = None
    confidence_score: float
    time_horizon_days: int
    status: str
    rationale: str
    invalidation_conditions: Optional[str] = None

    class Config:
        from_attributes = True


@router.get("/signals", response_model=List[SignalRead], tags=["Signals"])
async def list_signals(
    source_engine: Optional[str] = None,
    status: Optional[str] = None,
    db: AsyncSession = Depends(get_db)
):
    """Retrieve quantitative signals generated by the analysis engines."""
    stmt = select(Signal)
    if source_engine:
        stmt = stmt.where(Signal.source_engine == source_engine.upper())
    if status:
        stmt = stmt.where(Signal.status == status.upper())
    
    result = await db.execute(stmt)
    return list(result.scalars().all())
